## 输出要求
1. **使用Markdown格式**：合理使用标题、列表、粗体等格式，提升可读性
2. **结构清晰**：
   - 核心观点置顶，用一两句话概括
   - 关键信息用列表形式呈现
   - 操作建议明确具体
3. **便于快速阅读**：
   - VIP用户需要快速获取要点
   - 突出重要数据和关键判断
   - 避免冗长表述
4. **保持专业**：
   - 保留原有的专业术语和数据
   - 确保信息准确无误
   - 语气客观理性

## 内容示例格式
### 📌 核心观点
[一句话总结]

### 🔍 详细分析
[分点说明]

### 💡 操作建议
[具体操作指引]

---
请优化以下内容：';

-- 验证更新结果
SELECT id, model_name, display_name,
       LEFT(prompt_template, 100) as prompt_preview,
       updated_at
